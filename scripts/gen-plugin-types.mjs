#!/usr/bin/env node
// Emits the standalone `@voltius/plugin-types` declaration third-party plugin
// authors compile against. api.ts is the single source of truth; the four host
// types it imports are inlined so the output needs no host paths.
//
//   node scripts/gen-plugin-types.mjs [outFile]
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(resolve(root, p), "utf8");

/** Pull `export interface X {...}` / `export type X = ...;` out of a source file. */
function extract(src, name) {
  const iface = src.match(new RegExp(`export interface ${name} \\{[\\s\\S]*?\\n\\}`));
  if (iface) return iface[0];
  const alias = src.match(new RegExp(`export type ${name} =[^;]*;`));
  if (alias) return alias[0];
  throw new Error(`gen-plugin-types: could not find "${name}"`);
}

const types = read("src/types/index.ts");
const themes = read("src/themes/types.ts");
const locale = read("src/stores/localeStore.ts");

const preamble = [
  extract(types, "SerialConnectParams"),
  extract(types, "JumpHost"),
  extract(themes, "TerminalTheme"),
  extract(themes, "UITheme"),
  extract(themes, "AppTheme"),
  extract(locale, "Locale"),
].join("\n\n");

const api = read("src/plugins/api.ts")
  // The host-path imports are what the preamble above replaces.
  .replace(/^import type \{[^}]*\} from "@\/[^"]*";\n/gm, "")
  .replaceAll('import("@/types").JumpHost', "JumpHost");

const out = `// GENERATED by scripts/gen-plugin-types.mjs — do not edit by hand.
// Source of truth: src/plugins/api.ts in VoltiusApp/voltius.
import type { ReactNode } from "react";

${preamble}

${api.replace(/^import type \{ ReactNode \} from "react";\n/m, "")}
`;

const dest = resolve(root, process.argv[2] ?? "dist-plugin-types/index.d.ts");
mkdirSync(dirname(dest), { recursive: true });
writeFileSync(dest, out);
console.log(`[gen-plugin-types] wrote ${dest} (${out.split("\n").length} lines)`);
