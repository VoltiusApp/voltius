#!/usr/bin/env node
// Emits the standalone `@voltius/plugin-types` declaration third-party plugin
// authors compile against. api.ts is the single source of truth; the host
// types it imports or re-exports are inlined so the output needs no host paths.
//
//   node scripts/gen-plugin-types.mjs [outFile]
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(resolve(root, p), "utf8");

/**
 * Pull `export interface X {...}` / `export type X<T> = ...;` out of a source
 * file. Both forms allow generic parameters, and an interface must close on a
 * line of its own — a one-line `export interface X { a: string }` is not found.
 */
function extract(src, name) {
  const generics = "(?:<[^>]*>)?";
  const iface = src.match(new RegExp(`export interface ${name}${generics} \\{[\\s\\S]*?\\n\\}`));
  if (iface) return iface[0];
  // Ends on the first `;` that closes a line, not the first `;` at all: an
  // object-type alias carries `;` between its own members.
  const alias = src.match(new RegExp(`export type ${name}${generics} =[\\s\\S]*?;$`, "m"));
  if (alias) return alias[0];
  throw new Error(`gen-plugin-types: could not find "${name}"`);
}

const types = read("src/types/index.ts");
const themes = read("src/themes/types.ts");
const locale = read("src/stores/localeStore.ts");
const auditContext = read("src/services/auditContext.ts");
const domainResult = read("src/plugins/domains/result.ts");
const team = read("src/plugins/domains/team.ts");
const sharing = read("src/plugins/domains/sharing.ts");

const preamble = [
  extract(types, "SerialConnectParams"),
  extract(types, "JumpHost"),
  extract(themes, "TerminalTheme"),
  extract(themes, "UITheme"),
  extract(themes, "AppTheme"),
  extract(locale, "Locale"),
  extract(auditContext, "PluginAuditAction"),
  extract(domainResult, "DomainResult"),
  extract(team, "PluginTeam"),
  extract(team, "PluginTeamMember"),
  extract(team, "PluginMemberKeyState"),
  extract(team, "PluginTeamKeyStatus"),
  extract(sharing, "PluginSharedSession"),
].join("\n\n");

const api = read("src/plugins/api.ts")
  // The host-path imports and re-exports are what the preamble above replaces.
  // Host paths, absolute and relative alike: `./domains/*` does not exist in
  // the published package, so those types are inlined by the preamble too.
  .replace(/^(?:import|export) type \{[^}]*\} from "(?:@\/|\.\/)[^"]*";\n/gm, "")
  .replaceAll('import("@/types").JumpHost', "JumpHost");

const out = `// GENERATED by scripts/gen-plugin-types.mjs — do not edit by hand.
// Source of truth: src/plugins/api.ts in VoltiusApp/voltius.
/// <reference path="./ui.d.ts" />
import type { ReactNode } from "react";

${preamble}

${api.replace(/^import type \{ ReactNode \} from "react";\n/m, "")}
`;

const dest = resolve(root, process.argv[2] ?? "packages/plugin-types/index.d.ts");
mkdirSync(dirname(dest), { recursive: true });
writeFileSync(dest, out);
console.log(`[gen-plugin-types] wrote ${dest} (${out.split("\n").length} lines)`);
